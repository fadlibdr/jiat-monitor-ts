import { randomUUID } from 'node:crypto';
import { link, mkdir, open, readdir, readFile, rm, stat, utimes } from 'node:fs/promises';
import { dirname, join, relative, resolve, sep } from 'node:path';

/**
 * Where original photos live (HLD §8: stored as-is, never cropped or overwritten; the row keeps the
 * path). Local disk on the VPS for the pilot; an S3-compatible adapter can implement the same
 * interface once the provider is chosen (docs/remaining-work.md §6, decision 9).
 */
export interface ObjectStorage {
  put(key: string, bytes: Buffer, contentType: string): Promise<void>;
  get(key: string): Promise<Buffer>;
  delete(key: string): Promise<void>;
  /** objects under `prefix` (a key ending in "/"), for the orphan sweep; temp files of a crashed put included */
  list?(prefix: string): AsyncIterable<{ key: string; modifiedAt: Date }>;
}

/** Keys are generated by the app (company/…/sha256.ext); anything else is refused, never resolved. */
const KEY = /^[a-z0-9][a-z0-9/_.-]*$/i;

export class LocalDiskStorage implements ObjectStorage {
  private readonly root: string;

  constructor(root: string) {
    this.root = resolve(root);
  }

  /**
   * Atomic and never overwriting: the bytes go to a temp file (fsync'd), which is then hard-linked
   * to the final name. A crash mid-write leaves only a temp file, never a truncated original, so an
   * existing final file is always a complete copy — and keys are content-addressed (sha256), so it
   * is the same photo. contentType is for object stores; on disk the key's extension carries it.
   */
  async put(key: string, bytes: Buffer, _contentType?: string): Promise<void> {
    const path = this.path(key);
    await mkdir(dirname(path), { recursive: true });
    const tmp = `${path}.${randomUUID()}.tmp`;
    try {
      const fh = await open(tmp, 'wx');
      try {
        await fh.writeFile(bytes);
        await fh.sync();
      } finally {
        await fh.close();
      }
      try {
        await link(tmp, path);
      } catch (e) {
        if ((e as NodeJS.ErrnoException).code !== 'EEXIST') throw e;
        // the same photo again (an earlier save that never committed left it): make it look new, so
        // the orphan sweep's one-day grace starts over for the attachment about to reference it
        const at = new Date();
        await utimes(path, at, at);
      }
    } finally {
      await rm(tmp, { force: true });
    }
  }

  get(key: string): Promise<Buffer> {
    return readFile(this.path(key));
  }

  async delete(key: string): Promise<void> {
    await rm(this.path(key), { force: true });
  }

  async *list(prefix: string): AsyncIterable<{ key: string; modifiedAt: Date }> {
    if (!prefix.endsWith('/')) throw new Error(`Prefix storage harus diakhiri "/": ${prefix}`);
    const dir = this.path(prefix.slice(0, -1));
    let entries;
    try {
      entries = await readdir(dir, { recursive: true, withFileTypes: true });
    } catch (e) {
      if ((e as NodeJS.ErrnoException).code === 'ENOENT') return;
      throw e;
    }
    for (const ent of entries) {
      if (!ent.isFile()) continue;
      const full = join(ent.parentPath, ent.name);
      const key = relative(this.root, full).split(sep).join('/');
      yield { key, modifiedAt: (await stat(full)).mtime };
    }
  }

  private path(key: string): string {
    if (!KEY.test(key) || key.split('/').some((p) => p === '..' || p === '.' || p === '')) throw new Error(`Kunci storage tidak valid: ${key}`);
    const p = resolve(join(this.root, key));
    if (!p.startsWith(this.root + sep)) throw new Error(`Kunci storage di luar root: ${key}`);
    return p;
  }
}

/** Storage key of an intake photo: content-addressed, per company and month. */
export function intakeKey(companyId: number, sha256: string, mime: string, now: Date): string {
  const ext = mime === 'image/png' ? 'png' : mime === 'image/webp' ? 'webp' : 'jpg';
  const ym = `${now.getUTCFullYear()}/${String(now.getUTCMonth() + 1).padStart(2, '0')}`;
  return `company-${companyId}/intake/${ym}/${sha256}.${ext}`;
}
